#!/usr/bin/env node
/* Turns FORMS in js/config.js into SQL that upserts forms, form_zones and form_groups.
   Usage: node scripts/forms-sql.mjs > supabase/migrations/<timestamp>_forms_data.sql
   The browser's limit check and the database read the same numbers this way. */
import { pathToFileURL } from 'node:url';
import { FORMS } from '../js/config.js';

const holdsFreight = z => !z.na && !z.unavailable;
const q = s => `'${String(s).replace(/'/g, "''")}'`;

// Widest groups first; a group inside one already counted adds nothing.
export function capacityOf(form) {
  const counted = [];
  [...form.groups].sort((a, b) => b.zones.length - a.zones.length).forEach(g => {
    if (!counted.some(c => g.zones.every(id => c.zones.includes(id)))) counted.push(g);
  });
  const inGroup = new Set(counted.flatMap(g => g.zones));
  const loose = form.zones.filter(z => holdsFreight(z) && z.max && !inGroup.has(z.id));
  return counted.reduce((s, g) => s + g.max, 0) + loose.reduce((s, z) => s + z.max, 0);
}

export function formRows(forms) {
  const entries = Object.entries(forms);
  return {
    forms: entries.map(([id, f]) => ({ form_id: id, aircraft_type: f.type, name: f.name, is_split: !!f.split, capacity_lb: capacityOf(f) })),
    zones: entries.flatMap(([id, f]) => f.zones.filter(holdsFreight)
      .map((z, i) => ({ form_id: id, zone_id: z.id, label: z.label, max_lb: z.max ?? null, seq: i }))),
    groups: entries.flatMap(([id, f]) => f.groups
      .map(g => ({ form_id: id, group_id: g.id, label: g.short || g.label, zone_ids: g.zones, max_lb: g.max }))),
  };
}

export function formsSql(forms) {
  const { forms: fs, zones, groups } = formRows(forms);
  const v = x => x === null ? 'null' : typeof x === 'string' ? q(x) : Array.isArray(x) ? `array[${x.map(q).join(',')}]` : String(x);
  const values = rows => rows.map(r => `  (${Object.values(r).map(v).join(', ')})`).join(',\n');
  return `-- Generated by scripts/forms-sql.mjs from js/config.js. Do not edit by hand.
-- Illustrative limits, not from any real aircraft.

insert into public.forms (form_id, aircraft_type, name, is_split, capacity_lb) values
${values(fs)}
on conflict (form_id) do update set aircraft_type = excluded.aircraft_type, name = excluded.name,
  is_split = excluded.is_split, capacity_lb = excluded.capacity_lb;

insert into public.form_zones (form_id, zone_id, label, max_lb, seq) values
${values(zones)}
on conflict (form_id, zone_id) do update set label = excluded.label, max_lb = excluded.max_lb, seq = excluded.seq;
${groups.length ? `
insert into public.form_groups (form_id, group_id, label, zone_ids, max_lb) values
${values(groups)}
on conflict (form_id, group_id) do update set label = excluded.label, zone_ids = excluded.zone_ids, max_lb = excluded.max_lb;
` : ''}`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) process.stdout.write(formsSql(FORMS));
